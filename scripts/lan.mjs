import { spawnSync } from 'node:child_process';
import { networkInterfaces } from 'node:os';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { X509Certificate, createHash } from 'node:crypto';
import https from 'node:https';
import path from 'node:path';
import { selectLanAddress } from './lan-network.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'output', 'lan');
const certFile = path.join(output, 'common-ground-root.crt');
const compose = ['compose', '--env-file', '.env', '--env-file', '.env.lan', '-f', 'deploy/compose.lan.yaml'];
function run(command, args, quiet = false) {
  const result = spawnSync(command, args, { cwd: root, stdio: quiet ? 'pipe' : 'inherit', encoding: 'utf8', windowsHide: true });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${args.slice(0, 1).join(' ')} failed. ${quiet ? result.stderr || '' : 'See the output above.'}`);
  return result.stdout?.trim();
}
async function savedIP() {
  const config = await readFile(path.join(root, '.env.lan'), 'utf8');
  const ip = /^LAN_IP=(.+)$/m.exec(config)?.[1];
  if (!ip) throw new Error('LAN configuration is missing its address. Run npm run lan:up.');
  return selectLanAddress(networkInterfaces(), ip);
}
function probe(ip, ca) {
  return new Promise((resolve, reject) => {
    const request = https.get(`https://${ip}:8443/api/ready`, { ca, timeout: 5000 }, response => {
      let body = '';
      response.on('data', chunk => { body += chunk; });
      response.on('end', () => {
        try { resolve(response.statusCode === 200 && JSON.parse(body).ready === true); }
        catch { resolve(false); }
      });
    });
    request.on('timeout', () => request.destroy(new Error('HTTPS readiness timed out.')));
    request.on('error', reject);
  });
}
async function printLink(ip, certificate) {
  const fingerprint = new X509Certificate(certificate).fingerprint256;
  const message = `Common Ground - same-Wi-Fi sharing

Share this link: https://${ip}:8443

First visit on EACH device: install/trust common-ground-root.crt using LAN-SETUP.md.
Certificate SHA-256: ${fingerprint}
Certificate file SHA-256: ${createHash('sha256').update(certificate).digest('hex').toUpperCase()}
Share only the public .crt file; private keys stay in Docker.

Email verification: the host opens http://localhost:8025 and gives each friend ONLY their own verification link.
After signing in, use Invite to join the same workspace.
Keep this computer and Docker running. Rerun npm run lan:up if your Wi-Fi IP changes.
Stop: npm run lan:down | Return to localhost: npm run lan:local
`;
  await writeFile(path.join(output, 'SHARE.txt'), message);
  console.log(`\n${message}\nCertificate: ${certFile}\nInstructions: ${path.join(root, 'LAN-SETUP.md')}`);
}

async function main() {
  const [action = 'up', ...args] = process.argv.slice(2);
  if (action === 'up') {
    if (args.length && !(args.length === 2 && args[0] === '--ip')) throw new Error('Usage: npm run lan:up -- [--ip YOUR_WIFI_IP]');
    const ip = selectLanAddress(networkInterfaces(), args[1]);
    run('docker', ['info', '--format', '{{.ServerVersion}}'], true);
    run(process.execPath, ['scripts/docker-setup.mjs']);
    await writeFile(path.join(root, '.env.lan'), `# Generated by npm run lan:up. No secrets.\nLAN_IP=${ip}\n`);
    console.log(`Starting same-Wi-Fi HTTPS at https://${ip}:8443. Existing accounts are preserved.`);
    // Validate without dumping interpolated secrets into the terminal.
    run('docker', [...compose, 'config', '--quiet']);
    run('docker', [...compose, 'up', '--build', '-d', '--remove-orphans', '--wait', '--wait-timeout', '120']);
    // Compose does not recreate a container when only a bind-mounted file changes.
    run('docker', [...compose, 'exec', '-T', 'caddy', 'caddy', 'reload', '--config', '/etc/caddy/Caddyfile'], true);
    await mkdir(output, { recursive: true });
    let certificate;
    let lastError;
    for (let attempt = 0; attempt < 30; attempt++) {
      try {
        run('docker', [...compose, 'cp', 'caddy:/data/caddy/pki/authorities/local/root.crt', certFile], true);
        certificate = await readFile(certFile);
        if (await probe(ip, certificate)) { await printLink(ip, certificate); return; }
      } catch (error) { lastError = error; }
      await new Promise(resolve => setTimeout(resolve, 1000));
    }
    throw new Error(`LAN containers started, but verified HTTPS readiness failed. ${lastError?.message || ''} Check Docker and your private-network firewall; see LAN-SETUP.md.`);
  }
  if (args.length) throw new Error('Unexpected arguments.');
  if (action === 'link') {
    const ip = await savedIP();
    const certificate = await readFile(certFile);
    if (!await probe(ip, certificate)) throw new Error('App is not ready. Run npm run lan:up.');
    await printLink(ip, certificate);
  } else if (action === 'down') {
    run('docker', [...compose, 'down']);
    console.log('LAN sharing stopped. Accounts, backups and the certificate authority are retained.');
  } else if (action === 'local') {
    run('docker', ['compose', '-f', 'compose.yaml', 'up', '-d', '--remove-orphans', '--wait', '--wait-timeout', '120']);
    console.log('Local-only mode restored: http://localhost:8080');
  } else throw new Error('Use lan:up, lan:link, lan:down or lan:local.');
}
main().catch(error => { console.error(`\n${error.message}`); process.exitCode = 1; });
